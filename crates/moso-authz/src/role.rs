    /// A customer-defined role resolves into permissions the registry already
    /// declares — there is no bit for anything else.
    #[tokio::test]
    async fn direct_grants_compose_with_static_roles() {
        let source = MemoryRoleSource::<Role>::new();
        source.grant_permissions(
            ActorId::new("usr_1"),
            &Scope::Global,
            PermSet::of([Perm::AdminAccess]),
        );

        let extra = source
            .extra_permissions(&ActorId::new("usr_1"), &Scope::Global)
            .await
            .expect("permissions");

        assert_eq!(extra, PermSet::of([Perm::AdminAccess]));
        assert_eq!(
            Role::Viewer.permissions().union(extra).len(),
            Role::Viewer.permissions().len() + 1,
        );

        source.clear();
        assert!(source.is_empty());
    }

    /// Both halves of the source match scopes with [`Scope::covers`]. Matching
    /// by key string instead — which this used to do — agrees for `Global` and
    /// for an exact scope and disagrees the moment either side grows a rule,
    /// and a source that grants a role in one scope and its permissions in
    /// another is a source nobody can reason about.
    #[tokio::test]
    async fn direct_grants_and_roles_match_a_scope_the_same_way() {
        let acme = Scope::Org(ScopeId::new("acme"));
        let other = Scope::Org(ScopeId::new("other"));
        let alice = ActorId::new("usr_1");

        let source = MemoryRoleSource::<Role>::new()
            .granting(RoleAssignment::new(
                alice.clone(),
                Role::Viewer,
                Scope::Global,
            ))
            .granting(RoleAssignment::new(
                alice.clone(),
                Role::Admin,
                acme.clone(),
            ));
        source.grant_permissions(
            alice.clone(),
            &Scope::Global,
            PermSet::of([Perm::AdminAccess]),
        );
        source.grant_permissions(alice.clone(), &acme, PermSet::of([Perm::AdminSettings]));

        for scope in [Scope::Global, acme.clone(), other.clone()] {
            let roles = source.roles_for(&alice, &scope).await.expect("roles");
            let extra = source
                .extra_permissions(&alice, &scope)
                .await
                .expect("permissions");

            // A global grant reaches every scope, on both halves.
            assert!(roles.has(Role::Viewer), "{scope:?}");
            assert!(extra.has(Perm::AdminAccess), "{scope:?}");

            // A scoped grant reaches its own scope, on both halves.
            assert_eq!(
                roles.has(Role::Admin),
                extra.has(Perm::AdminSettings),
                "the two halves disagree about {scope:?}",
            );
            assert_eq!(roles.has(Role::Admin), scope == acme, "{scope:?}");
        }
    }

    /// The specific case the key-string form got wrong: a scope whose *key*
    /// happens to read as another one's is still a different scope.
    #[tokio::test]
    async fn a_direct_grant_does_not_leak_into_a_scope_that_only_looks_alike() {
        let alice = ActorId::new("usr_1");
        let team = Scope::Custom {
            kind: "org".to_owned(),
            id: ScopeId::new("acme"),
        };

        let source = MemoryRoleSource::<Role>::new();
        source.grant_permissions(alice.clone(), &team, PermSet::of([Perm::AdminSettings]));

        // `Scope::Org(acme)` and `Scope::Custom { kind: "org", id: acme }`
        // render the same key and are not the same scope. `covers` compares the
        // values; a key comparison could not tell them apart.
        assert_eq!(team.as_key(), Scope::Org(ScopeId::new("acme")).as_key());
        assert!(
            source
                .extra_permissions(&alice, &Scope::Org(ScopeId::new("acme")))
                .await
                .expect("permissions")
                .is_empty(),
        );
        assert!(
            !source
                .extra_permissions(&alice, &team)
                .await
                .expect("permissions")
                .is_empty(),
        );
    }

