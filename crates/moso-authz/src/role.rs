    async fn a_default_role_source_grants_nothing_extra() {
        struct Empty;

        impl RoleSource<Role> for Empty {
            fn roles_for<'a>(
                &'a self,
                _subject: &'a ActorId,
                _scope: &'a Scope,
            ) -> BoxFuture<'a, crate::Result<RoleSet<Role>>> {
                Box::pin(async { Ok(RoleSet::empty()) })
            }
        }

        let source = Empty;
        assert!(
            source
                .extra_permissions(&ActorId::new("usr_1"), &Scope::Global)
                .await
                .expect("permissions")
                .is_empty()
        );
        assert!(
            source
                .assignments(&ActorId::new("usr_1"))
                .await
                .expect("assignments")
                .is_empty()
        );
    }
