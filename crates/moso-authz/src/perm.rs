    // ── the performance claim ─────────────────────────────────────────────

    /// `docs/03-batteries/31-authorization.md`: a `PermSet` check is a bitwise
    /// AND, about a nanosecond, and the framework's overhead per authorization
    /// check is under a microsecond. This measures the check itself; the
    /// end-to-end figure is in `tests/overhead.rs`.
    ///
    /// The threshold is a thousand times the claim, so the test says "this is
    /// not accidentally a hash lookup" rather than "this machine is fast".
    #[test]
    fn a_permission_check_is_a_bitwise_and() {
        let held = PermSet::of([Perm::PostsRead, Perm::PostsUpdate, Perm::AdminAccess]);
        let rounds = 2_000_000;

        let started = std::time::Instant::now();
        let mut hits = 0_u64;
        for round in 0..rounds {
            let wanted = Perm::ALL[round % Perm::ALL.len()];
            hits += u64::from(held.has(wanted));
        }
        let each = started.elapsed() / rounds as u32;

        assert!(hits > 0, "the loop was optimised away");
        assert!(
            each < std::time::Duration::from_micros(1),
            "a permission check took {each:?}, which is not a bitwise AND",
        );
    }
