    /// Every argument mistake, with the "did you mean" that turns a typo into a
    /// one-character fix.
    #[test]
    fn every_argument_error_names_the_fix() {
        let unknown = expand_to_string(
            quote! { retires = 5 },
            quote! { async fn tidy(args: ()) -> Result { Ok(()) } },
        );
        assert!(unknown.contains("didyoumean`retries`"), "{unknown}");

        let bad_duration = expand_to_string(
            quote! { timeout = "2 minuts" },
            quote! { async fn tidy(args: ()) -> Result { Ok(()) } },
        );
        assert!(bad_duration.contains("isnotaduration"), "{bad_duration}");

        let bare_number = expand_to_string(
            quote! { timeout = "120" },
            quote! { async fn tidy(args: ()) -> Result { Ok(()) } },
        );
        assert!(bare_number.contains("isnotaduration"), "{bare_number}");

        let bad_backoff = expand_to_string(
            quote! { backoff = "exponentail(30s)" },
            quote! { async fn tidy(args: ()) -> Result { Ok(()) } },
        );
        assert!(bad_backoff.contains("isnotoneofthefour"), "{bad_backoff}");

        let bad_priority = expand_to_string(
            quote! { priority = "urgent" },
            quote! { async fn tidy(args: ()) -> Result { Ok(()) } },
        );
        assert!(bad_priority.contains("isnotapriority"), "{bad_priority}");
        assert!(
            bad_priority.contains("`low`,`normal`,`high`and`critical`"),
            "{bad_priority}"
        );

        // A one-character typo is close enough to suggest; `urgent` is not, and
        // a suggestion that fires on anything is noise rather than help.
        let near_miss = expand_to_string(
            quote! { priority = "hihg" },
            quote! { async fn tidy(args: ()) -> Result { Ok(()) } },
        );
        assert!(near_miss.contains("didyoumean`high`"), "{near_miss}");
    }

    /// The duration grammar has to agree with the runtime one, or a `timeout`
    /// and a `backoff` written the same way would mean different things.
    #[test]
    fn the_duration_grammar_matches_the_runtime_one() {
        assert_eq!(parse_humantime("500ms"), Some(500));
        assert_eq!(parse_humantime("30s"), Some(30_000));
        assert_eq!(parse_humantime("2m"), Some(120_000));
        assert_eq!(parse_humantime("1h"), Some(3_600_000));
        assert_eq!(parse_humantime("1h 30m"), Some(5_400_000));
        assert_eq!(parse_humantime("1d"), Some(86_400_000));
        assert_eq!(parse_humantime("1w"), Some(604_800_000));
        assert_eq!(parse_humantime("10 minutes"), Some(600_000));

        assert_eq!(parse_humantime(""), Some(0));
        assert_eq!(parse_humantime("120"), None, "a bare number is ambiguous");
        assert_eq!(parse_humantime("2 minuts"), None);
        assert_eq!(parse_humantime("s"), None);
        assert_eq!(parse_humantime("-5s"), None);
    }

