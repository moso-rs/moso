        assert!(out.contains("constSERIAL:bool=false"), "{out}");
        assert!(out.contains("typeArgs=SendWelcome"), "{out}");
        // The user's function is emitted unchanged, so it stays callable.
        assert!(out.contains("asyncfnsend_welcome_email"), "{out}");
